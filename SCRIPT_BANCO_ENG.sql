CREATE DATABASE IF NOT EXISTS ENGENHARIA_3;
USE ENGENHARIA_3;
CREATE TABLE ENGY(ID_ENG INT PRIMARY KEY,NOME_ENG VARCHAR(20) NOT NULL);

CREATE TABLE PROJETOY(ID_PROJ INT PRIMARY KEY, NOME_PROJ VARCHAR(25) NOT NULL, 
VALOR_PROJ DECIMAL);

CREATE TABLE ENGY_PROJY (ID_ENGY INT, ID_PROJY INT, CONSTRAINT FK_ID_ENGY_PROJY
FOREIGN KEY(ID_ENGY) REFERENCES ENGY(ID_ENG),CONSTRAINT FK_PROJY_ENGY FOREIGN KEY(ID_PROJY)
REFERENCES PROJETOY(ID_PROJ), CONSTRAINT PK_ENGY_PROJY PRIMARY KEY(ID_ENGY,ID_PROJY));

